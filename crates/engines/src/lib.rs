//! 平台能力层（engines）。
//!
//! 放置可插拔的平台能力（检索、爬虫、OCR 等），实现 `tpl-core` 定义的端口。
//! 模板刻意不内置任何具体能力，由派生项目按需添加。
//!
//! 在当前账号服务内部新增一项可插拔能力的步骤：
//!
//! 1. 在 `tpl-core` 里定义端口（trait）；
//! 2. 在本 crate 里实现它；
//! 3. 在 `tpl-accounts` 的装配代码里把实现接到用例上。
//!
//! 这些步骤只适用于账号服务内部的能力。新增独立业务域时，应在 `services/<module>/` 建立自己的装配入口、HTTP 契约和迁移，不要把它塞进账号服务的私有层。
